const STORAGE_KEY = "metromap-language";
const DEFAULT_LANGUAGE = "fr";

export function localizeLineName(name, translate) {
  const match = /^Ligne\s+(.+)$/i.exec(name);
  return match ? translate("line.name", { name: match[1] }) : name;
}

export function initializeLocalization() {
  const languageButtons = document.querySelectorAll("[data-language]");
  const listeners = new Set();
  let currentLanguage = DEFAULT_LANGUAGE;

  try {
    const savedLanguage = window.localStorage.getItem(STORAGE_KEY);
    if (Object.hasOwn(translations, savedLanguage)) {
      currentLanguage = savedLanguage;
    }
  } catch (error) {
    console.warn("Unable to read the saved language.", error);
  }

  function translate(key, values = {}) {
    const template = translations[currentLanguage][key] || translations[DEFAULT_LANGUAGE][key] || key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (
      Object.hasOwn(values, name) ? String(values[name]) : match
    ));
  }

  function applyTranslations() {
    document.documentElement.lang = currentLanguage;

    for (const element of document.querySelectorAll("[data-i18n]")) {
      const key = element.dataset.i18n;
      if (element.tagName === "TITLE") {
        document.title = translate(key);
      } else {
        element.textContent = translate(key);
      }
    }

    for (const element of document.querySelectorAll("[data-i18n-aria-label]")) {
      element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel));
    }

    for (const button of languageButtons) {
      const isSelected = button.dataset.language === currentLanguage;
      button.setAttribute("aria-pressed", String(isSelected));
    }
  }

  function setLanguage(language) {
    if (!Object.hasOwn(translations, language) || language === currentLanguage) {
      return;
    }

    currentLanguage = language;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch (error) {
      console.warn("Unable to save the selected language.", error);
    }

    applyTranslations();
    for (const listener of listeners) {
      listener(translate, currentLanguage);
    }
  }

  applyTranslations();
  for (const button of languageButtons) {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
  }

  return {
    translate,
    subscribe(listener) {
      listeners.add(listener);
      return () => listeners.delete(listener);
    }
  };
}
